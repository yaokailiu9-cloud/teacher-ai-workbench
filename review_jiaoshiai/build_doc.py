#!/usr/bin/env python3
# 依据 复刻规格.json 生成《复刻总纲.md》
import json, os

BASE = "/Users/nidie/Documents/ChatGPT/错题本/review_jiaoshiai"
spec = json.load(open(os.path.join(BASE, "复刻规格.json"), encoding="utf-8"))
tools = spec["tools"]

L = []
A = L.append
A("# 教师AI赋能站（jiaoshiai.top）复刻总纲\n")
A("> 复刻对象：<https://jiaoshiai.top/#workbench>　账号：123321　抓取时间：2026-09-12")
A("> 抓取方式：真实浏览器逐页快照 + DOM 结构解析 + 整页截图 + PDF 存档，全程未触发任何生成动作，未消耗积分。\n")

A("## 一、站点整体结构\n")
A("整站是一个单页外壳 + 24 个独立工具页的结构：\n")
A("```")
A("jiaoshiai.top/               首页（工作台入口，三板块聚合）")
A("jiaoshiai.top/#workbench     工作台锚点")
A("jiaoshiai.top/apps/<key>/    24 个独立工具页，各自独立可访问")
A("```\n")

A("### 1.1 首页分层\n")
A("| 区块 | 内容 |")
A("|---|---|")
A("| 顶部导航 | 站名「教师AI赋能站 / TEACHER AI WORKSTATION」、积分余额、用户名下拉、注册/登录、积分兑换 |")
A("| 首屏 Hero | 主标题「AI赋能教师提效、教学提分、教培增长。」、副标「教师工作的新基础设施 2026」、主按钮「进入教师工作台」 |")
A("| 板块 01 | **AI赋能教师提效** —— 把备课、资料和课堂制作变成可复用的工作流 |")
A("| 板块 02 | **AI赋能教学提分** —— 围绕审题、解题、得分与错因，建立教学提分闭环 |")
A("| 板块 03 | **AI赋能教培增长** —— 面向家长沟通与续班转化的诊断类工具 |")
A("| 工具卡 | 每卡含：MODULE 编号、计价单位（1 积分/次 或 /张 /5页 /批次）、工具名、一句话定位、一句话说明、「进入工具 ↗」 |\n")

A("### 1.2 全局系统\n")
A("- **账户**：用户名 + 密码登录，注册与登录共用一个弹窗（tab 切换），需勾选用户协议。")
A("- **积分**：右上角实时显示余额（当前账号 105 分）。每调用一次生成扣 1 积分，少数工具按量计价（题卷重排 1 积分/5 页、教辅图 1 积分/张、智批作业 1 积分/批次）。")
A("- **兑换码**：所有工具页表单底部都有「兑换码」输入框，占位符格式统一为 `TAI-XXXX-XXXX-XXXX-XXXX`；未登录时显示「立即兑换」按钮。")
A("- **未登录拦截**：直接访问 `/apps/<key>/` 会被重定向到 `/?login=1` 并弹出登录框。\n")
A("### 1.3 工具页公共骨架\n")
A("24 个工具页遵循同一套骨架，差异只在字段与结果区：\n")
A("```")
A("①  顶部导航（积分 / 用户名 / 兑换积分）")
A("②  标题区（工具名 + 一句话说明）")
A("③  输入区（年级、学科 等下拉 + 文件上传 + 补充说明文本域 + 兑换码）")
A("④  生成按钮（文案各工具不同，如「生成试卷」「开始审题分析」「拆解得分点」）")
A("⑤  结果区（分区块的报告结构，多数带 下载 PDF / 下载 Word）")
A("⑥  二次操作（重新生成 / 返回修改 / 组卷 / 去练习）")
A("└─ 无数据时结果区显示占位文案，如「等待生成解题路径」「预习单将在这里呈现」")
A("```\n")

A("## 二、板块与工具清单\n")
for cat, items in spec["categories"].items():
    A(f"### {cat}（{len(items)} 个）\n")
    A("| 编号 | 工具 | 路径 | 计价 |")
    A("|---|---|---|---|")
    for it in sorted(items, key=lambda x: x["编号"]):
        A(f"| {it['编号']} | {it['名称']} | `{it['路径']}` | {it['积分']} 积分 |")
    A("")

A("## 三、逐工具复刻细则\n")
A("每个工具给出：字段清单（含下拉全量选项）、操作按钮、模式切换、结果区结构。字段顺序即页面上从上到下的顺序。\n")

for t in tools:
    A(f"### {t['编号']}　{t['名称']}\n")
    A(f"- **路径**：`{t['路径']}`　**板块**：{t['板块']}　**计价**：{t['积分']} 积分")
    A(f"- **页面标题**：{t['页面标题']}")
    A(f"- **定位**：{t['副标题']}")
    A(f"- **说明**：{t['一句话说明']}\n")

    if t["模式切换"]:
        A(f"**模式切换**：{'、'.join(t['模式切换'])}\n")

    if t["输入字段"]:
        A("**输入区字段**\n")
        A("| 控件 | 名称 | 提示 / 说明 | 选项 |")
        A("|---|---|---|---|")
        for f in t["输入字段"]:
            opts = f.get("选项")
            if opts:
                o = "、".join(str(x) for x in opts[:30])
                if len(opts) > 30:
                    o += f" …（共 {len(opts)} 项）"
            else:
                o = "—"
            ph = f.get("提示", "—").replace("\n", " ")
            A(f"| {f['控件']}/{f['类型'] or '-'} | {f['名称'] or '—'} | {ph} | {o} |")
        A("")

    if t["操作按钮"]:
        A(f"**操作按钮**：{'　'.join(t['操作按钮'])}\n")

    if t["结果区结构"]:
        A(f"**结果区结构**：{' → '.join(t['结果区结构'])}\n")

    A(f"**存档**：`pages/{t['key']}/`（snapshot.txt 无障碍树、dom.json 结构、screenshot.png 整页截图、page.pdf）\n")
    A("---\n")

A("## 四、跨工具的共性规律\n")
A("1. **输入三段式**：年级/学科下拉 → 文件上传（PDF / DOCX / PNG / JPG，单文件 ≤50MB）→ 补充说明文本域，最后一行固定是兑换码。")
A("2. **题目类工具的三种出题粒度**：相似题 / 变式题 / 综合应用题，数量统一为 1~3 题的三个下拉。")
A("3. **结果区都是「分区块报告」**，典型骨架为：题目预览 → 逐项拆解（3~6 个编号区块）→ 结论/建议 → 导出。")
A("4. **导出统一为 PDF + Word 双通道**，部分额外支持复制结果、组卷、去练习。")
A("5. **生成中状态**：按钮文案切换为进行时并禁用，同时出现「取消」；长任务支持「暂停 / 继续 / 重试未完成的步骤」。")
A("6. **两种计价单位混用**：「次」按调用次数，「张 / 5页 / 批次」按产出量，落地时要区分扣费时机。\n")

A("## 五、存档清单\n")
A("| 路径 | 内容 |")
A("|---|---|")
A("| `复刻规格.json` | 24 个工具的机器可读结构规格 |")
A("| `复刻总纲.md` | 本文档 |")
A("| `复刻总览.html` | 可视化总览（含各页截图与结构） |")
A("| `api_sites.json` | 原站 `/api/sites` 返回的 24 条工具目录 |")
A("| `01_home_snapshot.txt` / `03_home_text.txt` | 首页无障碍树与文案 |")
A("| `pages/<key>/` | 每个工具页的快照、结构、截图、PDF |")

doc = "\n".join(L)
with open(os.path.join(BASE, "复刻总纲.md"), "w", encoding="utf-8") as fh:
    fh.write(doc)
print("已生成 复刻总纲.md，行数:", len(L))
